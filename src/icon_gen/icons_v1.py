# l x1 y1 x2 y2 w | a cx cy r start sweep w   (描邊, 角度同 GDI+ 順時針為正)
import math

def xpoly(cx, cy, r, t):
    """× 形多邊形（旋轉 45° 的十字）"""
    h = t / 2
    pts = [(-h, -r), (h, -r), (h, -h), (r, -h), (r, h), (h, h), (h, r), (-h, r), (-h, h), (-r, h), (-r, -h), (-h, -h)]
    c, s = math.cos(math.pi / 4), math.sin(math.pi / 4)
    out = []
    for x, y in pts:
        out += [round(cx + x * c - y * s, 1), round(cy + x * s + y * c, 1)]
    return 'p ' + ' '.join(f'{v:g}' for v in out)

